  /// True bila [point] berada di dalam wilayah Kabupaten Jeneponto.
  static bool contains(Coordinate point) {
    if (!point.isValid) return false;
    if (point.latitude < minLatitude ||
        point.latitude > maxLatitude ||
        point.longitude < minLongitude ||
        point.longitude > maxLongitude) {
      return false;
    }
    for (final ring in boundaryPolygons) {
      if (_pointInRing(point, ring)) return true;
    }
    return false;
  }

  /// Kecamatan yang memuat [point], atau null bila tidak terdeteksi.
  static JenepontoDistrict? districtAt(Coordinate point) {
    for (final district in districts) {
      if (district.contains(point)) return district;
    }
    return null;
  }

  /// Kecamatan terdekat dari [point] (fallback ketika batas tidak presisi).
  static JenepontoDistrict nearestDistrict(Coordinate point) {
    JenepontoDistrict nearest = districts.first;
    double best = point.distanceToKm(nearest.center);
    for (final district in districts.skip(1)) {
      final double distance = point.distanceToKm(district.center);
      if (distance < best) {
        best = distance;
        nearest = district;
      }
    }
    return nearest;
  }

  /// Cari kecamatan berdasarkan nama (case-insensitive).
  static JenepontoDistrict? districtByName(String? name) {
    if (name == null || name.trim().isEmpty) return null;
    final String normalized = name.trim().toLowerCase();
    for (final district in districts) {
      if (district.name.toLowerCase() == normalized) return district;
    }
    return null;
  }

  /// Daftar nama kecamatan untuk dropdown.
  static List<String> get districtNames =>
      districts.map((district) => district.name).toList(growable: false);
}

/// Ray-casting point-in-polygon sederhana (ring tertutup tidak wajib).
bool _pointInRing(Coordinate point, List<Coordinate> ring) {
  bool inside = false;
  for (int i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    final double xi = ring[i].longitude;
    final double yi = ring[i].latitude;
    final double xj = ring[j].longitude;
    final double yj = ring[j].latitude;
    final bool intersects = ((yi > point.latitude) != (yj > point.latitude)) &&
        (point.longitude < (xj - xi) * (point.latitude - yi) / (yj - yi) + xi);
    if (intersects) inside = !inside;
  }
  return inside;
}
